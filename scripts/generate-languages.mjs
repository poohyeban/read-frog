// Sources: GPLv3 src/locales/en.yml and MIT iso-639-3 (see LICENSES/iso-639-3.txt).
// Node's ICU/CLDR supplies canonical BCP 47 aliases, native names and direction.
import fs from "node:fs"
import { createRequire } from "node:module"
import { iso6393To1 } from "iso-639-3"
const require = createRequire(import.meta.url)
const yaml = require(require.resolve("yaml", { paths: [require.resolve("@wxt-dev/i18n")] }))
const names = Object.fromEntries(
  Object.entries(yaml.parse(fs.readFileSync("src/locales/en.yml", "utf8")).languages).map(
    ([key, value]) => [key === "cmnHant" ? "cmn-Hant" : key, value],
  ),
)
const iso = {},
  native = {},
  rtl = []
for (const [code, name] of Object.entries(names)) {
  const locale = new Intl.Locale(
    code === "cmn-Hant" ? "zh-Hant" : code === "cmn" ? "zh-Hans" : code,
  )
  const short = iso6393To1[code] ?? locale.language
  if (short.length === 2) iso[code] = code === "cmn-Hant" ? "zh-TW" : short
  native[code] =
    new Intl.DisplayNames([locale.baseName], { type: "language", fallback: "none" }).of(
      locale.baseName,
    ) ?? name
  if (locale.getTextInfo().direction === "rtl") rtl.push(code)
}
fs.writeFileSync(
  "src/utils/language-data.ts",
  `// Generated by scripts/generate-languages.mjs; GPLv3 names, MIT ISO data, ICU/CLDR aliases.\nexport const languageNames = ${JSON.stringify(names, null, 2)} as const\nexport const iso6391 = ${JSON.stringify(iso, null, 2)} as const\nexport const nativeNames = ${JSON.stringify(native, null, 2)} as const\nexport const rtlCodes = ${JSON.stringify(rtl)} as const\n`,
)
